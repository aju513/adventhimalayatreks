       document.addEventListener('DOMContentLoaded', function() {
           // Header Sticky
           const scrollThreshold = 300;
           const header = document.querySelector('.header__menu');
           const headerHeightElement = document.querySelector('.header-height');
           const headerHeight = 59;

           const handleHeaderSticky = () => {
               if (header) {
                   if (window.innerWidth <= 1023) {
                       header.classList.remove('sticky');
                       return;
                   }
                   if (window.scrollY > scrollThreshold) {
                       header.classList.add('sticky');
                       headerHeightElement.style.height = `${headerHeight}px`;
                   } else {
                       header.classList.remove('sticky');
                       headerHeightElement.style.height = '0';
                   }
               }
           };

           // Dropdown Toggle
           const handleDropdownToggle = (event) => {
               const toggle = event.currentTarget;
               const dropdown = toggle.nextElementSibling;

               document.querySelectorAll('.dropdown').forEach((otherDropdown) => {
                   if (otherDropdown !== dropdown) {
                       otherDropdown.classList.add('hidden');
                       otherDropdown.previousElementSibling
                           ?.querySelector('.icon')
                           ?.classList.remove('rotate-180');
                   }
               });

               dropdown.classList.toggle('hidden');
               toggle.querySelector('.icon')?.classList.toggle('rotate-180');
           };

           document.querySelectorAll('.dropdown-toggle').forEach((toggle) => {
               toggle.addEventListener('click', handleDropdownToggle);
           });

           // Close dropdown when clicking outside (for anchors)
           document.addEventListener('mousedown', (e) => {
               if (e.target.tagName.toLowerCase() === 'a') {
                   document.querySelectorAll('.dropdown').forEach((dropdown) => {
                       dropdown.classList.add('hidden');
                   });
                   document.querySelectorAll('.dropdown-toggle .icon').forEach((icon) => {
                       icon.classList.remove('rotate-180');
                   });
               }
           });

           // Sticky Header Scroll Listener
           window.addEventListener('scroll', handleHeaderSticky);

           // Menu Button Toggle
           const menu = document.querySelector('.menu');
           const menuButton = document.querySelector('.menu-button');
           if (menuButton && menu) {
               menuButton.addEventListener('click', (e) => {
                   e.preventDefault();
                   menu.classList.toggle('open');
               });
           }

           // Mobile Menu Accordion
           document.querySelectorAll('.open-menu').forEach((button) => {
               button.addEventListener('click', (e) => {
                   e.preventDefault();
                   const menu = button.nextElementSibling;
                   menu.style.maxHeight =
                       menu.style.maxHeight === '10000px' ? '0' : '10000px';
                   button.classList.toggle('rotate');
               });
           });

           // Modal Close (search)
           document.addEventListener('mousedown', (event) => {
               const modalContent = document.querySelector('.modal-content');
               if (modalContent && !modalContent.contains(event.target)) {
                   modalContent.closest('.modal-dialog')?.classList.remove('is-active');
               }
           });

           // Search Toggle
           const searchBtn = document.querySelector('.search-btn');
           const searchClose = document.querySelector('.search-close');
           const searchBox = document.querySelector('.search-box-elements');

           if (searchBtn && searchBox) {
               searchBtn.addEventListener('click', () => {
                   searchBox.classList.toggle('hidden');
               });
           }

           if (searchClose && searchBox) {
               searchClose.addEventListener('click', (e) => {
                   e.preventDefault();
                   searchBox.classList.add('hidden');
               });
           } // <- MISSING BRACKET FIXED HERE ✅

           // Menu cross toggle (nav-open)
           const menuToggle = document.querySelector('.menu-toggle');
           if (menuToggle) {
               menuToggle.addEventListener('click', () => {
                   document.body.classList.toggle('nav-open');
               });
           }

           // Mobile navbar sticky
           window.addEventListener('scroll', () => {
               const mobNav = document.querySelector('.mob-nav');
               if (mobNav) {
                   if (window.scrollY > 100) {
                       mobNav.classList.add('sticky');
                   } else {
                       mobNav.classList.remove('sticky');
                   }
               }
           });

           // Custom Dropdown
           const dropdown = document.querySelector('.custom-dropdown');
           const selected = dropdown?.querySelector('.selected');
           const options = dropdown?.querySelector('.options');

           const closeDropdown = () => {
               dropdown?.classList.remove('active');
           };

           if (dropdown && selected && options) {
               dropdown.addEventListener('click', () => {
                   dropdown.classList.toggle('active');
               });

               options.addEventListener('click', (e) => {
                   if (e.target.tagName === 'LI') {
                       selected.textContent = e.target.textContent;
                       closeDropdown();
                   }
               });

               window.addEventListener('click', (e) => {
                   if (!dropdown.contains(e.target)) {
                       closeDropdown();
                   }
               });
           }

           // Tab switching

           const tabItems = document.querySelectorAll('.tab-item');
           const tabs = {};

           tabItems.forEach((item) => {
               const tabId = item.getAttribute('data-tab');
               const tabContent = document.querySelector(`#${tabId}`);
               if (tabContent) {
                   tabs[tabId] = tabContent;
               } else {
                   console.warn(`No tab content found with id="${tabId}"`);
               }
           });

           function activateTab(tabId) {
               tabItems.forEach((i) =>
                   i.classList.toggle('active', i.getAttribute('data-tab') === tabId),
               );
               Object.keys(tabs).forEach((key) => {
                   tabs[key].classList.toggle('hidden', key !== tabId);
               });
           }

           tabItems.forEach((item) => {
               item.addEventListener('click', () => {
                   const tabId = item.getAttribute('data-tab');
                   activateTab(tabId);
               });
           });

           if (tabItems.length > 0) {
               const firstTabId = tabItems[0].getAttribute('data-tab');
               activateTab(firstTabId);
           }
       });
